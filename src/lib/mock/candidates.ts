/**
 * A plausible stage timeline for a candidate, built from the canonical stage order
 * up to (and including) their current stage. Static, but data-driven so detail
 * screens don't need hand-authored timelines per candidate.
 */
export function candidateTimeline(candidate: Candidate): StageEvent[] {
  if (candidate.stage === "rejected") {
    return [
      { stage: "sourced", enteredOn: candidate.appliedOn },
      { stage: "rejected", enteredOn: candidate.appliedOn, current: true },
    ];
  }
  const reachedIndex = STAGE_ORDER.indexOf(candidate.stage);
  const reached = STAGE_ORDER.slice(0, reachedIndex + 1);
  const applied = new Date(candidate.appliedOn).getTime();
  const day = 86_400_000;
  return reached.map((stage: StageKey, i) => ({
    stage,
    enteredOn: new Date(applied + i * 3 * day).toISOString().slice(0, 10),
    current: i === reached.length - 1,
    note: i === reached.length - 1 ? `In ${stageLabels[stage]} · ${candidate.daysInStage}d` : undefined,
  }));
}
